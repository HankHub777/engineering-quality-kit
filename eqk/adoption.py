"""`eqk plan`, `eqk apply`, `eqk revert`.

Contract: apply only CREATES files that do not exist. It never edits, reformats or deletes
existing files. Every created file is recorded with its hash so revert can remove exactly
what eqk added, and refuses to remove anything a human has since edited.
"""

from __future__ import annotations

import difflib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path

from . import __version__
from . import profiles as profiles_mod
from .inspection import detect
from .util import resolve_tool, sha256_file

QUALITY_DIR = ".quality"
MANIFEST = f"{QUALITY_DIR}/applied.json"
CONFIG = f"{QUALITY_DIR}/eqk.json"

QUALITY_GITIGNORE = (
    "# Generated by engineering-quality-kit: run outputs are evidence, not source.\nevidence/\nreports/\ncache/\n"
)


def check_applicability(check: dict, info: dict) -> tuple[bool, str]:
    lang = check.get("applies_to")
    if lang and lang not in info["languages"]:
        return False, f"no {lang} files detected"
    req = check.get("requires")
    if req and not info["configs"].get(req):
        return False, f"requires {req} (not present in repo)"
    return True, "applicable"


def build_plan(root: Path, profile_id: str) -> dict:
    prof = profiles_mod.load(profile_id)
    info = detect(root)
    actions: list[dict] = []
    warnings: list[str] = []

    if (root / MANIFEST).exists():
        warnings.append(
            "eqk is already applied here (.quality/applied.json exists); run `eqk revert` first to change profile"
        )
    if info["git"]["is_repo"] and info["git"]["dirty"]:
        warnings.append(
            "working tree has uncommitted changes; commit or stash them first so eqk's changes are reviewable on their own"
        )
    if not info["git"]["is_repo"]:
        warnings.append(
            "not a git repository: revert still works via the manifest, but there is no commit to diff against"
        )

    config = {"profile": prof["id"], "profile_version": prof["version"], "eqk_version": __version__}
    desired = [
        (CONFIG, json.dumps(config, indent=2) + "\n", "records the selected profile for `eqk verify`"),
        (
            f"{QUALITY_DIR}/.gitignore",
            QUALITY_GITIGNORE,
            "keeps run evidence out of commits without touching the repo's own .gitignore",
        ),
    ]
    for sc in prof.get("scaffold", []):
        lang = sc.get("applies_to")
        if lang and lang not in info["languages"]:
            continue
        existing = info["configs"].get(sc["skip_if"], [])
        if existing:
            actions.append(
                {
                    "op": "keep",
                    "path": sc["path"],
                    "reason": f"existing {sc['skip_if']} found ({', '.join(existing)}); it is preserved and used as-is",
                }
            )
            continue
        desired.append(
            (sc["path"], profiles_mod.template(sc["template"]), f"no {sc['skip_if']} found; adds a minimal one")
        )

    for rel, content, reason in desired:
        if (root / rel).exists():
            actions.append({"op": "keep", "path": rel, "reason": "file already exists; eqk never overwrites"})
        else:
            actions.append({"op": "create", "path": rel, "reason": reason, "content": content})

    for key in ("ci", "pre_commit"):
        for f in info["configs"].get(key, []):
            actions.append(
                {"op": "keep", "path": f, "reason": f"existing {key.replace('_', '-')} config; eqk does not modify it"}
            )

    checks = []
    for c in prof["checks"]:
        ok, why = check_applicability(c, info)
        path, source = resolve_tool(c["tool"], root)
        checks.append(
            {
                "id": c["id"],
                "tool": c["tool"],
                "gate": c["gate"],
                "applicable": ok,
                "reason": why,
                "tool_found": path is not None,
                "tool_source": source,
                "install_hint": None if path or not ok else c.get("install_hint"),
            }
        )
        if ok and path is None:
            warnings.append(
                f"{c['id']}: tool '{c['tool']}' not found; verify will report it as unavailable "
                f"(not passed). Install: {c.get('install_hint')}"
            )
    return {
        "profile": {"id": prof["id"], "version": prof["version"]},
        "languages": info["languages"],
        "actions": actions,
        "checks": checks,
        "warnings": warnings,
    }


def render_plan(plan: dict) -> str:
    lines = [f"# eqk plan — profile {plan['profile']['id']} {plan['profile']['version']} (nothing changed yet)", ""]
    lines.append("File actions:")
    for a in plan["actions"]:
        lines.append(f"  [{a['op']:6}] {a['path']} — {a['reason']}")
    lines += ["", "Checks `eqk verify` will run:"]
    for c in plan["checks"]:
        state = "skip (n/a)" if not c["applicable"] else ("ready" if c["tool_found"] else "TOOL MISSING")
        lines.append(f"  - {c['id']:<18} {'gate' if c['gate'] else 'info':4}  {state:12} {c['reason']}")
    if plan["warnings"]:
        lines += ["", "Warnings:"] + [f"  ! {w}" for w in plan["warnings"]]
    diffs = [a for a in plan["actions"] if a["op"] == "create"]
    if diffs:
        lines += ["", "Diff (new files only):"]
        for a in diffs:
            lines += [
                ln.rstrip("\n")
                for ln in difflib.unified_diff(
                    [], a["content"].splitlines(keepends=True), "/dev/null", "b/" + a["path"]
                )
            ]
    lines += ["", "Apply with: eqk apply --profile " + plan["profile"]["id"] + " --yes", "Undo later with: eqk revert"]
    return "\n".join(lines)


def apply(root: Path, profile_id: str) -> dict:
    plan = build_plan(root, profile_id)
    if (root / MANIFEST).exists():
        raise RuntimeError("already applied (.quality/applied.json exists); run `eqk revert` first")
    created = []
    for a in plan["actions"]:
        if a["op"] != "create":
            continue
        target = root / a["path"]
        if target.exists():  # appeared after planning: still never overwrite
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "x", encoding="utf-8", newline="\n") as fh:  # 'x' = fail if it exists
            fh.write(a["content"])
        created.append({"path": a["path"], "sha256": sha256_file(target)})
    manifest = {
        "eqk_version": __version__,
        "profile": plan["profile"],
        "applied_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "created": created,
        "modified": [],
        "deleted": [],
    }
    (root / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return {"plan": plan, "manifest": manifest}


def revert(root: Path, force: bool = False) -> dict:
    mpath = root / MANIFEST
    if not mpath.is_file():
        raise RuntimeError("nothing to revert: .quality/applied.json not found")
    manifest = json.loads(mpath.read_text(encoding="utf-8"))
    removed, kept = [], []
    for item in manifest["created"]:
        p = root / item["path"]
        if not p.exists():
            continue
        if sha256_file(p) != item["sha256"] and not force:
            kept.append({"path": item["path"], "reason": "edited since apply; keeping it (use --force to remove)"})
            continue
        p.unlink()
        removed.append(item["path"])
    if kept:
        return {"removed": removed, "kept": kept, "complete": False}
    # Generated run outputs are gitignored by eqk itself; remove them with the rest.
    for sub in ("evidence", "reports", "cache"):
        shutil.rmtree(root / QUALITY_DIR / sub, ignore_errors=True)
    mpath.unlink()
    qdir = root / QUALITY_DIR
    if qdir.is_dir() and not any(qdir.iterdir()):
        qdir.rmdir()
    return {"removed": removed, "kept": [], "complete": True}
